"""Private temporary storage for uploads (PRD UP-3).

Keys are generated by the server (`uploads/<32 hex chars>`) and validated on
every call, so clients never choose or influence storage paths. The
interface is shaped for two kinds of backend:

- direct upload (LocalStorage): the client PUTs the bytes to the API, which
  streams them into storage under a hard size cap (`receive()`);
- presigned upload (S3/R2, Phase 7): `upload_target()` returns a short-lived
  presigned URL, the client uploads straight to the bucket, and the API only
  checks the object afterwards (`size()`, `local_copy()`).
"""

from __future__ import annotations

import re
import secrets
from collections.abc import AsyncIterator, Iterator
from contextlib import AbstractContextManager
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Protocol

UPLOAD_PREFIX = "uploads"
KEY_PATTERN = re.compile(rf"^{UPLOAD_PREFIX}/[0-9a-f]{{32}}$")


class StorageError(Exception):
    pass


class InvalidKey(StorageError):
    pass


class ObjectTooLarge(StorageError):
    """The upload stream passed the size cap; nothing was kept."""


def new_upload_key() -> str:
    return f"{UPLOAD_PREFIX}/{secrets.token_hex(16)}"


def check_key(key: str) -> str:
    if not isinstance(key, str) or not KEY_PATTERN.match(key):
        raise InvalidKey("invalid storage key")
    return key


@dataclass(frozen=True)
class UploadTarget:
    """Where and how the client sends the video bytes."""

    method: str
    url: str
    expires_at: datetime
    max_bytes: int
    headers: dict[str, str] = field(default_factory=dict)
    # True when the URL is an API endpoint that needs the job's bearer token;
    # False for presigned URLs, which carry their own short-lived signature.
    requires_access_token: bool = True


class Storage(Protocol):
    supports_direct_upload: bool

    def upload_target(
        self, key: str, job_id: str, expires_at: datetime, max_bytes: int
    ) -> UploadTarget: ...

    async def receive(self, key: str, chunks: AsyncIterator[bytes], max_bytes: int) -> int:
        """Store a streamed upload; raises ObjectTooLarge past max_bytes. Returns its size."""
        ...

    def size(self, key: str) -> int | None:
        """Object size in bytes, or None if it does not exist."""
        ...

    def local_copy(self, key: str) -> AbstractContextManager[Path]:
        """A local file path for the object while the context is open."""
        ...

    def delete(self, key: str) -> bool:
        """Delete the object; True if it no longer exists afterwards."""
        ...

    def stale_keys(self, older_than: datetime) -> Iterator[str]:
        """Keys of objects last modified before `older_than` (orphan sweep)."""
        ...
